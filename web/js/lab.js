function lineChart(series, labels, options = {}) {
  const width = 620;
  const height = options.height || 200;
  const left = 44;
  const right = 12;
  const top = 14;
  const bottom = 28;
  const all = series.flatMap((line) => line).filter(Number.isFinite);
  const low = Math.min(...all);
  const high = Math.max(...all);
  const range = high - low || 1;
  const chart = svgElement("svg", { viewBox: `0 0 ${width} ${height}`, class: "result-visual", role: "img", "aria-label": options.aria || "Generated values chart" });
  [0, 1, 2, 3].forEach((index) => {
    const y = top + (height - top - bottom) * index / 3;
    chart.append(svgElement("line", { x1: left, y1: y, x2: width - right, y2: y, class: "chart-grid" }));
  });
  series.forEach((line, lineIndex) => {
    const points = line.map((value, index) => {
      const x = left + (width - left - right) * (line.length === 1 ? 0 : index / (line.length - 1));
      const y = top + (height - top - bottom) * (1 - (value - low) / range);
      return `${x},${y}`;
    }).join(" ");
    chart.append(svgElement("polyline", { points, class: lineIndex === 0 ? "chart-line" : "chart-baseline", fill: "none" }));
  });
  const labelIndices = labels.length > 10
    ? [0, Math.floor((labels.length - 1) / 4), Math.floor((labels.length - 1) / 2), Math.floor((labels.length - 1) * 3 / 4), labels.length - 1]
    : labels.map((_, index) => index);
  labelIndices.forEach((index) => {
    const x = left + (width - left - right) * index / Math.max(1, labels.length - 1);
    chart.append(svgElement("text", { x, y: height - 8, "text-anchor": "middle", class: "chart-label" }, labels[index]));
  });
  if (options.legend) {
    options.legend.forEach((label, index) => {
      const x = left + index * 190;
      chart.append(svgElement("text", { x, y: 12, class: "chart-label" }, label));
    });
  }
  return chart;
}

