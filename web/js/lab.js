function esc(value) {
  return String(value).replace(/[&<>"']/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  }[character]));
}

function linkedTerms(text) {
  const keys = Object.keys(GLOSSARY).sort((a, b) => b.length - a.length);
  const expression = new RegExp(`\\b(${keys.map((key) => key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|")})\\b`, "ig");
  let html = "";
  let offset = 0;
  for (const match of text.matchAll(expression)) {
    html += esc(text.slice(offset, match.index));
    const key = match[0].toLowerCase();
    html += `<button class="glossary-term" type="button" data-glossary="${esc(key)}">${esc(match[0])}</button>`;
    offset = match.index + match[0].length;
  }
  return html + esc(text.slice(offset));
}

