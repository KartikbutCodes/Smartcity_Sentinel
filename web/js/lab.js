function applyPreset(card, preset) {
  const id = card.dataset.experiment;
  switch (id) {
    case "route": {
      const [start, end] = preset.split("|");
      state.routeStart = start;
      state.routeEnd = end;
      updateRouteChoice();
      break;
    }
    case "priority":
      if (preset === "routine") {
        setControl(card, "severity", 0.2); setControl(card, "impact", 0.25); setControl(card, "confidence", 0.7);
      } else {
        setControl(card, "severity", 0.95); setControl(card, "impact", 0.9); setControl(card, "confidence", 0.95);
      }
      break;
    case "plate":
      setControl(card, "text", preset);
      break;
    case "speed":
      if (preset === "short") {
        setControl(card, "x1", 40); setControl(card, "y1", 30); setControl(card, "x2", 100); setControl(card, "y2", 30); setControl(card, "elapsed", 2);
      } else {
        setControl(card, "x1", 20); setControl(card, "y1", 20); setControl(card, "x2", 240); setControl(card, "y2", 100); setControl(card, "elapsed", 4);
      }
      break;
    case "crowd":
      state.crowdPoints = [];
      if (preset === "scatter") {
        for (let index = 0; index < 24; index += 1) {
          const x = ((index * 37 + 13) % 97) / 97;
          const y = ((index * 61 + 29) % 97) / 97;
          state.crowdPoints.push([x, y]);
        }
      }
      drawCrowdInput();
      break;
    case "anomaly":
      if (preset === "typical") {
        setControl(card, "power", 78); setControl(card, "pressure", 320); setControl(card, "vibration", 0.26);
      } else {
        setControl(card, "power", 118); setControl(card, "pressure", 215); setControl(card, "vibration", 1.35);
      }
      break;
    case "spot-anomaly":
      runExperiment(card);
      break;
    case "forecast":
      state.forecastSeries = preset === "rise" ? [12, 14, 17, 18, 20, 23, 24, 27] : [25, 28, 26, 34, 41, 38, 48, 57, 55, 62, 70, 76];
      card.querySelector("[data-series-label]").textContent = `Series: ${preset === "rise" ? "steady rise" : "busy period"} / ${state.forecastSeries.length} values`;
      break;
    case "rul":
      state.rulSeries = preset === "slow" ? [1, 2, 3, 4, 5] : [3, 8, 15, 24, 35];
      card.querySelector("[data-rul-label]").textContent = `Series: ${preset === "slow" ? "slow wear" : "fast wear"}`;
      setControl(card, "threshold", preset === "slow" ? 8 : 40);
      setControl(card, "rate", preset === "slow" ? 1 : 11);
      break;
    case "privacy":
      setControl(card, "epsilon", preset === "more-noise" ? 0.2 : 2);
      break;
    case "audit":
      state.selectedAuditBlock = Number(preset);
      document.querySelectorAll("[data-audit-block]").forEach((button) => button.classList.toggle("is-selected", Number(button.dataset.auditBlock) === state.selectedAuditBlock));
      break;
    case "roles":
    case "fairness":
      runExperiment(card);
      break;
    case "edge":
      if (preset === "small") {
        setControl(card, "frameBytes", 500000); setControl(card, "metadataBytes", 256); setControl(card, "frameCount", 60);
      } else {
        setControl(card, "frameBytes", 1800000); setControl(card, "metadataBytes", 1200); setControl(card, "frameCount", 120);
      }
      break;
    case "fedavg":
      if (preset === "unequal") {
        setControl(card, "countA", 20); setControl(card, "countB", 80);
      } else {
        setControl(card, "countA", 50); setControl(card, "countB", 50);
      }
      break;
    case "qlearning":
      setControl(card, "episodes", Number(preset));
      break;
    case "video":
      card.dataset.scenario = preset;
      card.querySelectorAll("[data-preset]").forEach((button) => button.classList.toggle("is-selected", button.dataset.preset === preset));
      break;
  }
}

